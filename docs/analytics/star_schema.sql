-- Veritas analytics: a star schema for reporting, kept apart from the app's own tables.
--
-- The app database (backend/migrations) is normalised for writing: 41 tables, each fact
-- stored once. This schema is shaped for reading: 5 fact tables (events, many rows) that
-- share 4 dimension tables (descriptions, few rows). Every question in the README's metrics
-- section is one fact table plus at most a few one-step joins.
--
-- Generated from one spec together with metadata.yml; the README explains every table.
-- Naming:
--   dim_<thing>                Dimension table: the who, what, where and when that facts are described by. Singular noun: dim_project, not dim_projects.
--   fact_<event>               Fact table: one row per business event or measurement. Named after the event: fact_donation, fact_release.
--   <dim>_key                  Surrogate key: a small whole number made by the warehouse, the primary key of a dimension and the foreign key in facts (project_key).
--   <thing>_id                 Natural key: the id the app database already uses (a UUID), kept so every row can be traced back (project_id).
--   date_key, <role>_date_key  A day as the number yyyymmdd (20261108). Several dates on one fact get a role prefix: released_date_key, paid_date_key.
--   <amount>_qapik             Money, as a whole number of qəpik (₼1 = 100 qəpik). Never a float, so totals are exact.
--   <thing>_count              A count, added up across rows.
--   is_<state>                 Yes/no flag (boolean).
--   days_<from>_to_<to>        A duration in days, with one decimal.
--   pk_, fk_, uq_, ck_, ix_    Constraint and index names: pk_<table>, fk_<table>_<column>, uq_<table>_<column>, ck_<table>_<rule>, ix_<table>_<column>.
--   row 0                      Every dimension has a row with key 0 for 'none': the guest donor, no target project, the whole project, a date that has not happened yet. Fact keys are therefore never empty.
--
-- Run it on any PostgreSQL 14+ database: psql -f docs/analytics/star_schema.sql

CREATE SCHEMA IF NOT EXISTS analytics;
COMMENT ON SCHEMA analytics IS 'Veritas reporting star schema: dim_ tables describe, fact_ tables measure. Money is in qəpik (₼1 = 100).';

-- ------------------------------------------------------------------ dim_date
-- Dimension. One row is one calendar day, in Baku time (UTC+4).
CREATE TABLE analytics.dim_date (
    date_key               integer CONSTRAINT pk_dim_date PRIMARY KEY,
    full_date              date CONSTRAINT uq_dim_date_full_date UNIQUE,
    year                   smallint,
    quarter                smallint,
    month                  smallint,
    month_name             text,
    iso_week               smallint,
    day_of_week            smallint,
    day_name               text,
    is_weekend             boolean,
    CONSTRAINT ck_dim_date_quarter CHECK (quarter BETWEEN 1 AND 4),
    CONSTRAINT ck_dim_date_month CHECK (month BETWEEN 1 AND 12),
    CONSTRAINT ck_dim_date_iso_week CHECK (iso_week BETWEEN 1 AND 53),
    CONSTRAINT ck_dim_date_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_dim_date_key_matches_date CHECK ((date_key = 0 AND full_date IS NULL) OR date_key = (EXTRACT(YEAR FROM full_date) * 10000 + EXTRACT(MONTH FROM full_date) * 100 + EXTRACT(DAY FROM full_date))::integer)
);
COMMENT ON TABLE analytics.dim_date IS 'The calendar. Facts point here instead of storing dates, so ''by month'' or ''weekends only'' is a plain filter. One row is one calendar day, in Baku time (UTC+4). Source: Generated by generate_series in star_schema.sql, 2025 to 2030. No app table. History: none: a day never changes.';
COMMENT ON COLUMN analytics.dim_date.date_key IS 'The day as yyyymmdd. 0 means ''not yet''.';
COMMENT ON COLUMN analytics.dim_date.full_date IS 'The day itself. Empty only on row 0.';
COMMENT ON COLUMN analytics.dim_date.year IS 'Calendar year.';
COMMENT ON COLUMN analytics.dim_date.quarter IS 'Quarter of the year, 1 to 4.';
COMMENT ON COLUMN analytics.dim_date.month IS 'Month, 1 to 12.';
COMMENT ON COLUMN analytics.dim_date.month_name IS 'Month name in English.';
COMMENT ON COLUMN analytics.dim_date.iso_week IS 'ISO week number, 1 to 53.';
COMMENT ON COLUMN analytics.dim_date.day_of_week IS '1 = Monday ... 7 = Sunday (ISO).';
COMMENT ON COLUMN analytics.dim_date.day_name IS 'Day name in English.';
COMMENT ON COLUMN analytics.dim_date.is_weekend IS 'Saturday or Sunday.';

-- ------------------------------------------------------------------ dim_donor
-- Dimension. One row is one donor account; row 0 stands for every guest who gave without an account.
CREATE TABLE analytics.dim_donor (
    donor_key              integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_dim_donor PRIMARY KEY,
    donor_id               uuid CONSTRAINT uq_dim_donor_donor_id UNIQUE,
