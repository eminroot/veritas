COMMENT ON COLUMN analytics.dim_donor.donor_id IS 'The account''s id in the app (users.id). Pseudonymous: it identifies an account, not a person, unless joined back to the app database.';
COMMENT ON COLUMN analytics.dim_donor.sign_in_method IS 'How the account signs in: email (a password), google, phone (a code sent by text, in the phone app) or guest.';
COMMENT ON COLUMN analytics.dim_donor.joined_date IS 'The day the account was made (Baku time). Empty for guests.';
COMMENT ON COLUMN analytics.dim_donor.is_guest IS 'True only on row 0.';

