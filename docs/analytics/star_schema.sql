COMMENT ON TABLE analytics.dim_donor IS 'Who gave, without saying who they are: no name, email or phone is copied here. One row is one donor account; row 0 stands for every guest who gave without an account. Source: users (app database). A donor is a user with at least one donation. History: type 1: a change overwrites the row (sign-in method is the only attribute that can change).';
